import { readFileSync, writeFileSync } from "fs";
import { prerenderChangelog, renderChangelogFeed } from "./landing-discovery.mjs";

const homeJs = readFileSync("dist-landing/home.js", "utf-8");
const changelogJs = readFileSync("dist-landing/changelog.js", "utf-8");
const css = readFileSync("dist-landing/landing.css", "utf-8");
const landingHtml = readFileSync("src/landing/home.html", "utf-8");
const changelogHtml = prerenderChangelog(
  readFileSync("src/landing/changelog.html", "utf-8"),
  changelogJs,
);
const changelogFeed = renderChangelogFeed(JSON.parse(readFileSync("changelog.json", "utf-8")));
const llmsText = readFileSync("docs-site/public/llms.txt", "utf-8");

const output = `// Generated by scripts/embed-landing-build.mjs — do not edit manually
export const LANDING_HTML = ${JSON.stringify(landingHtml)};
export const CHANGELOG_HTML = ${JSON.stringify(changelogHtml)};
export const CHANGELOG_FEED = ${JSON.stringify(changelogFeed)};
export const LLMS_TXT = ${JSON.stringify(llmsText)};

export const LANDING_ASSETS: Record<string, { content: string; contentType: string }> = {
  "home.js": { content: ${JSON.stringify(homeJs)}, contentType: "application/javascript" },
  "changelog.js": { content: ${JSON.stringify(changelogJs)}, contentType: "application/javascript" },
  "landing.css": { content: ${JSON.stringify(css)}, contentType: "text/css" },
};
`;

writeFileSync("src/runtime/landing-bundle.ts", output);
console.log("landing-bundle.ts written");
